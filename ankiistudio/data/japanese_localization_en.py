def localize_card_fields(template_key: str, card: dict[str, object]) -> dict[str, object]:
    localized = dict(card)
    word = str(localized.get("word") or "")
    translation = str(localized.get("translation") or "")
    explanation = str(localized.get("explanation") or "")
    localized["section"] = localize_section(str(localized.get("section") or ""))

    if template_key == "basic_phrases":
        localized["translation"] = BASIC_PHRASE_EN.get(word, PT_TRANSLATION_TO_EN.get(translation, translation))
    else:
        localized["translation"] = PT_TRANSLATION_TO_EN.get(translation, translation)

    if explanation:
        if explanation.startswith("Kanji comum:"):
            localized["explanation"] = "Common kanji:" + explanation[len("Kanji comum:"):]
        elif explanation.startswith("Kanji possível:"):
            localized["explanation"] = "Possible kanji:" + explanation[len("Kanji possível:"):]
        elif explanation.startswith("Kanji:"):
            localized["explanation"] = explanation
        else:
            localized["explanation"] = EXPLANATION_PT_TO_EN.get(explanation, explanation)
    return localized
